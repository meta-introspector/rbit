//! The sidebar beside an issue or pull request: assignees, labels, milestone,
//! notifications and deletion.
use super::super::fallback::{MessageFamily, MessageWriter};

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum IssueSidebarMessage {
    Relationships,
    Subissue,
    ParentIssue,
    BlockedBy,
    Blocking,
    Blocked,
    CompletedSubissues,
    VisibleRelationsHint,
    AddRelationship,
    RelationKind,
    RelatedRepository,
    RelatedNumber,
    RemoveRelationship,
    NoRelationships,

    Assignees,
    NoOne,
    AssignYourself,
    EditAssignees,
    SaveAssignees,
    Labels,
    NoneYet,
    EditLabels,
    NoRepositoryLabels,
    SaveLabels,
    Milestone,
    NoMilestone,
    ChangeMilestone,
    SaveMilestone,
    Notifications,
    Subscribe,
    Unsubscribe,
    NotNotifiedIssue,
    NotNotifiedPull,
    /// The accessible name of the delete section.
    Danger,
    DeleteIssue,
    DeletePull,
    DeleteIssueConfirm,
    DeletePullConfirm,
    /// Why the viewer is notified about the thread.
    ReasonManual,
    ReasonComment,
    ReasonReviewed,
    ReasonAuthor,
    ReasonMention,
    ReasonAssigned,
    ReasonReviewRequested,
}

